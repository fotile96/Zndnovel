main = function()
    comSectionCardStart(gameSave.fragmentDoSceneId, gameSave.fragmentDoCardId)
    if gameSave.myCard[1].hold == -1 then
        oCard.mesNot()
        run(cGetFileName("script", "snr_fragment_main"))
        quit()
    end
    card_2_s1s_20_intro()
    local l1_0 = 0
    local l1_1 = 0
    local l1_2 = -1
    while l1_0 < 1 do
        local l1_3 = oCard.selectCardObj()
        if l1_3 == 1 then
            break
        end
        if l1_3 == -1 then
            oCard.cancelCard()
            comSectionCardEnd(gameSave.fragmentDoSceneId, gameSave.fragmentDoCardId)
            run(cGetFileName("script", "snr_fragment_main"))
            quit()
        end
        if l1_1 == 1 then
            oCard.mesNG()
            vms(1890, "NONVOICE", "【彩野】「……」")
            comPoseDelete()
            wait(5)
        end
        if l1_1 == 0 then
            oCard.mesNG()
            l1_1 = l1_1 + 1
            comPoseDelete()
        end
        wait(30)
    end
    card_2_s1s_20_resolve()
    run(cGetFileName("script", "snr_mainmenu"))
    quit()
end
