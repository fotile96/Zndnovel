-- 空白卡演出（抄 oCard.show 的动画姿势，但不产生 18000+ 消息；文本由调用方在停留期发出）
finShowBlankCard = function(p0)
    layerLoad(layerName.pose1, cGetFileName("card", "crd_0_d"))
    layerAlpha(layerName.pose1, 0)
    layerPosition(layerName.pose1, -400, 40)
    layerMovePosition(layerName.pose1, 130, 40, 30)
